#!/bin/bash
set -euo pipefail

# =============================================================================
# experiment-init.sh — One-time workspace setup for iteration loop
# =============================================================================
#
# Usage: ./experiment-init.sh <project_name> <goals_file> [options]
#
# Options:
#   --challenge-rules <file>  Path to challenge rules file (default: built-in)
#   --resume                  Validate existing workspace, don't overwrite
#   --model <model>           Override spec model
#   --help                    Show usage
#
# =============================================================================

source "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/lib.sh"

# -----------------------------------------------------------------------------
# Argument parsing
# -----------------------------------------------------------------------------

usage() {
    cat << EOF
Usage: $(basename "$0") <project_name> <goals_file> [options]

Arguments:
  project_name          Name for the experiment (e.g., doc-ingest)
  goals_file            Path to markdown file with qualitative goals

Options:
  --challenge-rules <file>  Custom challenge rules file
  --resume                  Resume existing workspace (don't overwrite)
  --model <model>           Override spec agent model (default: $SPEC_MODEL)
  --help                    Show this help

Example:
  $(basename "$0") doc-ingest GOALS.md
  $(basename "$0") doc-ingest goals-draft.md --challenge-rules custom-rules.conf
  $(basename "$0") --resume doc-ingest GOALS.md
EOF
    exit 0
}

PROJECT_NAME=""
GOALS_FILE=""
CHALLENGE_RULES_FILE=""
RESUME=false

while [[ $# -gt 0 ]]; do
    case $1 in
        --challenge-rules)
            CHALLENGE_RULES_FILE="$2"
            shift 2
            ;;
        --resume)
            RESUME=true
            shift
            ;;
        --model)
            SPEC_MODEL="$2"
            shift 2
            ;;
        --help|-h)
            usage
            ;;
        -*)
            log_error "Unknown option: $1"
            ;;
        *)
            if [[ -z "$PROJECT_NAME" ]]; then
                PROJECT_NAME="$1"
            elif [[ -z "$GOALS_FILE" ]]; then
                GOALS_FILE="$1"
            else
                log_error "Too many arguments"
            fi
            shift
            ;;
    esac
done

# Validate arguments
[[ -z "$PROJECT_NAME" ]] && log_error "Missing project_name. Run with --help for usage."
[[ -z "$GOALS_FILE" ]] && log_error "Missing goals_file. Run with --help for usage."
[[ -f "$GOALS_FILE" ]] || log_error "Goals file not found: $GOALS_FILE"

# Validate git repo
git rev-parse --git-dir > /dev/null 2>&1 || log_error "Not in a git repository"

CURRENT_BRANCH=$(git branch --show-current)

echo -e "\n${GREEN}Experiment Init — Iteration Loop Setup${NC}"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "  Project:  $PROJECT_NAME"
echo "  Goals:    $GOALS_FILE"
echo "  Branch:   $CURRENT_BRANCH"
echo "  Model:    $SPEC_MODEL"
[[ "$RESUME" = true ]] && echo "  Mode:     RESUME"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"

# -----------------------------------------------------------------------------
# Resume mode: validate existing workspace
# -----------------------------------------------------------------------------

if [[ "$RESUME" = true ]]; then
    log_step "Resume mode — validating existing workspace"

    MISSING=()
    [[ -f GOALS.md ]] || MISSING+=("GOALS.md")
    [[ -f experiment-log.md ]] || MISSING+=("experiment-log.md")
    [[ -f iteration-count ]] || MISSING+=("iteration-count")

    if [[ ${#MISSING[@]} -gt 0 ]]; then
        log_error "Resume failed — missing files: ${MISSING[*]}"
    fi

    log_info "Workspace valid. iteration-count=$(cat iteration-count)"
    log_step "Resume complete"
    echo ""
    echo "Next steps:"
    echo "  ./outer-loop.sh --max 1    # Run one iteration"
    echo "  ./outer-loop.sh --max 5    # Run five iterations"
    echo ""
    exit 0
fi

# -----------------------------------------------------------------------------
# Step 1: Clean old Ralph artifacts (FR-9)
# -----------------------------------------------------------------------------

log_step "Step 1: Cleaning old Ralph artifacts"
log_timestamp "START cleanup"

CLEANED=()

for f in DESIGN.md DESIGN_v1.md DESIGN_REVIEW.md ralph-init.log loop.sh; do
    if [[ -f "$f" ]]; then
        rm -f "$f"
        CLEANED+=("$f")
    fi
done

# Wipe old specs (will be regenerated by IterationSpecAgent)
if [[ -d specs ]] && ls specs/*.md >/dev/null 2>&1; then
    rm -f specs/*.md
    CLEANED+=("specs/*.md")
fi

# Wipe stale iteration artifacts from prior experiments
for f in eval-report*.md iteration-brief.md IMPLEMENTATION_PLAN.md; do
    if [[ -f "$f" ]]; then
        rm -f "$f"
        CLEANED+=("$f")
    fi
done

if [[ ${#CLEANED[@]} -gt 0 ]]; then
    log_info "Removed: ${CLEANED[*]}"
else
    log_info "No old artifacts to clean"
fi

# Verify preserved files
for f in src tests AGENTS.md pyproject.toml; do
    if [[ -e "$f" ]]; then
        log_info "Preserved: $f"
    fi
done

log_timestamp "END   cleanup"

# -----------------------------------------------------------------------------
# Step 2: Create workspace artifacts
# -----------------------------------------------------------------------------

log_step "Step 2: Creating workspace artifacts"
log_timestamp "START workspace creation"

# Copy goals (skip if same file)
if [[ "$(realpath "$GOALS_FILE")" != "$(realpath GOALS.md 2>/dev/null)" ]]; then
    cp "$GOALS_FILE" GOALS.md
    log_info "Created: GOALS.md (from $GOALS_FILE)"
else
    log_info "GOALS.md already in place"
fi

# Create experiment-log.md
cat > experiment-log.md << EOF
# Experiment Log — $PROJECT_NAME

## Goals
$(cat GOALS.md)

EOF
log_info "Created: experiment-log.md"

# Create iteration-count
echo "0" > iteration-count
log_info "Created: iteration-count (set to 0)"

# Create experiment-history directory
mkdir -p experiment-history
log_info "Created: experiment-history/"

# Create specs directory
mkdir -p specs
log_info "Created: specs/"

log_timestamp "END   workspace creation"

# -----------------------------------------------------------------------------
# Step 3: Challenge rules
# -----------------------------------------------------------------------------

log_step "Step 3: Writing challenge-rules.conf"

if [[ -n "$CHALLENGE_RULES_FILE" ]] && [[ -f "$CHALLENGE_RULES_FILE" ]]; then
    cp "$CHALLENGE_RULES_FILE" challenge-rules.conf
    log_info "Copied custom challenge rules from $CHALLENGE_RULES_FILE"
else
    cat > challenge-rules.conf << 'EOF'
ADD_PDF_PER_ITERATION=1
INITIAL_CORPUS=tests/corpus/papers.jsonl
PDF_POOL_DIR=tests/corpus/pool/
EOF
    log_info "Created default challenge-rules.conf for doc-ingest"
fi

# -----------------------------------------------------------------------------
# Step 4: Update .gitignore
# -----------------------------------------------------------------------------

log_step "Step 4: Updating .gitignore"

GITIGNORE_ADDITIONS="
# Experiment artifacts (large/temp)
*.pdf
.env
tests/corpus/pool/"

if [[ -f .gitignore ]]; then
    # Only add entries that aren't already present
    while IFS= read -r line; do
        [[ -z "$line" ]] && continue
        [[ "$line" == \#* ]] && continue
        if ! grep -qF "$line" .gitignore 2>/dev/null; then
            echo "$line" >> .gitignore
            log_info "Added to .gitignore: $line"
        fi
    done <<< "$GITIGNORE_ADDITIONS"
else
    echo "$GITIGNORE_ADDITIONS" > .gitignore
    log_info "Created .gitignore with experiment entries"
fi

# -----------------------------------------------------------------------------
# Step 5: Strip ## Status section from AGENTS.md
# -----------------------------------------------------------------------------

log_step "Step 5: Updating AGENTS.md"

if [[ -f AGENTS.md ]]; then
    if grep -q '^## Status' AGENTS.md; then
        # Strip everything from "## Status" to the next "## " heading (or end of file)
        awk '
        /^## Status/ { skip = 1; next }
        /^## / && skip { skip = 0 }
        !skip { print }
        ' AGENTS.md > AGENTS.md.tmp
        mv AGENTS.md.tmp AGENTS.md
        log_info "Stripped ## Status section from AGENTS.md"
    else
        log_info "No ## Status section found in AGENTS.md — no changes needed"
    fi
else
    log_info "No AGENTS.md found — skipping"
fi

# -----------------------------------------------------------------------------
# Step 6: Commit
# -----------------------------------------------------------------------------

log_step "Step 6: Committing workspace"

git add -A
if ! git diff --cached --quiet 2>/dev/null; then
    git commit -m "experiment-init: set up iteration loop for $PROJECT_NAME

Created workspace artifacts:
- GOALS.md (qualitative goals)
- experiment-log.md (iteration history)
- iteration-count (starting at 0)
- challenge-rules.conf (progressive challenge)
- experiment-history/ (archive directory)

Cleaned old Ralph artifacts.
Updated AGENTS.md (stripped status section).
Updated prompt templates for iteration loop."
    log_info "Committed workspace setup"
else
    log_info "No changes to commit"
fi

# -----------------------------------------------------------------------------
# Summary
# -----------------------------------------------------------------------------

echo -e "\n${GREEN}━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━${NC}"
echo -e "${GREEN}✓ Experiment workspace ready!${NC}"
echo -e "${GREEN}━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━${NC}\n"

echo "Created files:"
echo "  GOALS.md                 — Qualitative goals"
echo "  experiment-log.md        — Iteration history"
echo "  iteration-count          — Current iteration (0)"
echo "  challenge-rules.conf     — Progressive challenge config"
echo "  experiment-history/      — Archive directory"
echo "  PROMPT_iteration_spec.md — IterationSpecAgent prompt"
echo "  PROMPT_eval.md           — EvalAgent prompt"
echo "  PROMPT_plan.md           — Plan agent prompt (updated)"
echo "  PROMPT_build.md          — Build agent prompt (updated)"
echo "  lib.sh                   — Shared utilities"
echo ""
echo "Prerequisites:"
echo "  - Populate tests/corpus/pool/ with candidate PDFs for progressive challenge"
echo "  - Verify AGENTS.md has correct operational guidance"
echo ""
echo "Next steps:"
echo "  ./outer-loop.sh --max 1    # Run one iteration (smoke test)"
echo "  ./outer-loop.sh --max 3    # Run three iterations"
echo ""
