"""Show `agentic-mbse validate` output is unchanged between two agentic-mbse revisions.

    uv run python scripts/subset_profile/validate_diff.py --base a718efec --final REV [--out PATH]

Plan Phase 10, spec "Consumer output is unchanged". Each revision is exported with `git archive`
into its own temp tree and synced there (`uv sync --frozen`), so each runs its own code. Both run
`agentic-mbse validate --complete --verbose` on the same inputs:

- every `tests/fixtures/` directory that holds `.sysml` files at the base revision, read from the
  base export (the fixtures Item 1 did not add), and
- dc3 `models/` at `808464df` (baseline) and `60b44d53` (repaired), each exported once.

Output text is normalized only by replacing each temp-tree prefix with a placeholder. The result
is a markdown report with every difference, written to the item's `evidence/validate-diff.md`.
"""

from __future__ import annotations

import argparse
import difflib
import os
import subprocess
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from probe import child_env, export_tree, read_license_key, resolve_rev  # noqa: E402

REPO_ROOT = Path(__file__).resolve().parents[2]
DC3_REPO = Path.home() / "src" / "dc3"
DC3_TREES = {
    "dc3-baseline": "808464df85d50521e4fbb9ba7cceb63d382aa832",
    "dc3-repaired": "60b44d53460fccd2f44811d8abfd42bc270e90b2",
}
DEFAULT_OUT = (
    REPO_ROOT
    / ".project"
    / "completed"
    / "20261018_exec-subset-profile"
    / "evidence"
    / "validate-diff.md"
)
TIMEOUT_S = 1800


def build(rev: str, dest: Path, env: dict[str, str]) -> Path:
    export_tree(REPO_ROOT, rev, dest)
    sync = subprocess.run(
        ["uv", "sync", "--frozen"], cwd=dest, env=env, capture_output=True, text=True
    )
    if sync.returncode != 0:
        raise SystemExit(f"uv sync --frozen failed in {dest}:\n{sync.stdout}{sync.stderr}")
    return dest / ".venv" / "bin" / "agentic-mbse"


def validate(cli: Path, target: Path, env: dict[str, str], prefixes: dict[str, str]) -> str:
    run = subprocess.run(
        [str(cli), "validate", "--complete", "--verbose", str(target)],
        cwd=target.parent,
        env=env,
        capture_output=True,
        text=True,
        timeout=TIMEOUT_S,
    )
    text = f"exit={run.returncode}\n{run.stdout}{run.stderr}"
    for prefix, placeholder in prefixes.items():
        text = text.replace(prefix, placeholder)
    return text


def fixture_dirs(tree: Path) -> list[Path]:
    root = tree / "tests" / "fixtures"
    return sorted(d for d in root.iterdir() if d.is_dir() and any(d.rglob("*.sysml")))


def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--base", required=True)
    parser.add_argument("--final", required=True)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args()
    base, final = resolve_rev(REPO_ROOT, args.base), resolve_rev(REPO_ROOT, args.final)
    env = child_env(read_license_key())
    for var in (
        "VIRTUAL_ENV",
        "PYTHONPATH",
        "PYTHONHOME",
        "UV_PROJECT_ENVIRONMENT",
        "CONDA_PREFIX",
    ):
        env.pop(var, None)

    with tempfile.TemporaryDirectory(prefix="validate-diff-") as tmp:
        work = Path(tmp)
        clis = {base: build(base, work / "base", env), final: build(final, work / "final", env)}
        inputs = {f"tests/fixtures/{d.name}": d for d in fixture_dirs(work / "base")}
        for label, rev in DC3_TREES.items():
            export_tree(DC3_REPO, rev, work / label)
            inputs[f"{label} models/"] = work / label / "models"
        prefixes = {
            str(work / "base"): "<agentic-tree>",
            str(work / "final"): "<agentic-tree>",
            str(work): "<tmp>",
        }
        report = [
            "# `agentic-mbse validate` before and after Item 1",
            "",
            "Generated by `scripts/subset_profile/validate_diff.py`.",
            "",
            f"- Base: agentic-mbse `{base}`. Final: agentic-mbse `{final}`. Each from its own `git archive` export and `uv sync --frozen`.",
            "- Command: `agentic-mbse validate --complete --verbose <input>`. Fixture inputs are read from the base export, so both revisions see identical files.",
            f"- dc3 trees: baseline `{DC3_TREES['dc3-baseline']}`, repaired `{DC3_TREES['dc3-repaired']}`.",
            "",
            "| Input | Base exit | Identical |",
            "|---|---|---|",
        ]
        diffs = []
        for name, target in inputs.items():
            before = validate(clis[base], target, env, prefixes)
            after = validate(clis[final], target, env, prefixes)
            same = before == after
            report.append(
                f"| `{name}` | {before.splitlines()[0]} | {'yes' if same else '**NO**'} |"
            )
            print(f"{name}: {'identical' if same else 'DIFFERS'}")
            if not same:
                diffs += [f"### {name}", "", "```diff"]
                diffs += list(
                    difflib.unified_diff(
                        before.splitlines(), after.splitlines(), "base", "final", lineterm=""
                    )
                )
                diffs += ["```", ""]
        differing = sum(1 for line in diffs if line.startswith("### "))
        summary = (
            f"**{differing} of {len(inputs)} inputs differ.**"
            if differing
            else f"**All {len(inputs)} inputs identical.**"
        )
        report += ["", summary, ""]
        report += diffs
    args.out.write_text("\n".join(report).rstrip() + "\n", encoding="utf-8")
    print(f"wrote {args.out}")
    return 1 if diffs else 0


if __name__ == "__main__":
    os.umask(0o022)
    raise SystemExit(main())
