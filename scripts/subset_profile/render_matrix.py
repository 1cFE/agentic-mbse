"""Render the capability/refusal matrix and the rule records to a markdown evidence file.

    uv run python scripts/subset_profile/render_matrix.py [--out PATH]

Reads `tests/fixtures/subset_profile/inventory/matrix.toml` (through the one loader,
`tests/helpers/subset_matrix.py`) and the packaged rule records, and writes
`.project/active/exec-subset-profile/evidence/matrix.md` by default. Pure: no SysIDE.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO_ROOT))

from agentic_mbse.sysml.subset_profile import PACKAGED_RULES, Outcome, RuleRecord  # noqa: E402
from tests.helpers.subset_matrix import (  # noqa: E402
    DC3_ITEMS,
    UPSTREAM_ITEMS,
    Matrix,
    MatrixRow,
    SiteStatus,
    load_matrix,
)

DEFAULT_OUT = REPO_ROOT / ".project" / "active" / "exec-subset-profile" / "evidence" / "matrix.md"


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _record_lines(rule: RuleRecord, shapes: tuple[str, ...]) -> list[str]:
    lines = []
    for shape_id in shapes:
        shape = rule.shape(shape_id)
        by_outcome = {
            outcome.value: ", ".join(c.value for c in shape.contexts_with(outcome))
            for outcome in Outcome
            if shape.contexts_with(outcome)
        }
        recorded = (
            "; ".join(f"{o}: {c}" for o, c in by_outcome.items()) or "every context unconfirmed"
        )
        sa1 = " SA-1 statement." if shape.no_admitted_context else ""
        lines.append(f"  - `{shape_id}`: {recorded}.{sa1}")
    return lines


def _row_section(row: MatrixRow) -> list[str]:
    lines = [f"### {row.row_id}: {row.title}", ""]
    lines.append(f"- **Class:** `{row.cls.value}`" + (f", rule `{row.rule}`" if row.rule else ""))
    lines.append(f"- **Outcome:** `{row.outcome.value}` in: {'; '.join(row.contexts)}")
    if row.rule:
        lines.append("- **Record contexts by shape:**")
        lines.extend(_record_lines(PACKAGED_RULES.rule(row.rule), row.shapes))
    for split in row.split:
        lines.append(
            f"- **Split:** {split.count} × {split.label} → `{split.outcome.value}` (`{split.shape}`)"
        )
    lines.append(f"- **Evidence status:** `{row.evidence_status.value}`")
    lines.append("- **Evidence:** " + ", ".join(f"`{e}`" for e in row.evidence))
    lines.append(f"- **Owner:** {row.owner}")
    lines.append(
        f"- **Coverage limitation:** {row.coverage_limitation or 'none (implemented in Item 1)'}"
    )
    if row.statement:
        lines.append(f"- **Notes:** {row.statement}")
    if row.l2_relation:
        lines.append(f"- **Relation to L2:** {row.l2_relation}")
    if row.site_status is not SiteStatus.LISTED:
        lines.append(f"- **Sites:** none (`{row.site_status.value}`)")
    else:
        lines.append(
            f"- **Sites:** {len(row.sites)}"
            + (": " + ", ".join(f"`{s}`" for s in row.sites) if row.sites else "")
        )
    lines.append("")
    return lines


def render(matrix: Matrix) -> str:
    identity = PACKAGED_RULES.verified_against
    out = [
        "# Capability/refusal matrix (EXEC-SUBSET-CONTRACT Item 1)",
        "",
        "Generated by `scripts/subset_profile/render_matrix.py` from `tests/fixtures/subset_profile/inventory/matrix.toml` and the packaged rule records. Do not edit by hand.",
        "",
        f"Records verified against sysml-codegen `{identity.codegen_rev}`, agentic-mbse `{identity.agentic_rev}`, SysIDE {identity.syside_version}.",
        "",
        "## Summary",
        "",
        "| Row | Class | Rule | Outcome | Evidence | Owner | dc3 | Upstream |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for row in matrix.values():
        out.append(
            f"| {row.row_id} | {row.cls.value} | {row.rule or ''} | {row.outcome.value} | "
            f"{row.evidence_status.value} | {_cell(row.owner)} | {', '.join(row.dc3)} | {', '.join(row.upstream)} |"
        )
    out += ["", "## dc3 cross-references", "", "| Item | Rows |", "|---|---|"]
    for item in sorted(DC3_ITEMS, key=lambda i: int(i[1:])):
        out.append(f"| {item} | {', '.join(sorted(matrix.by_dc3(item)))} |")
    for item in sorted(UPSTREAM_ITEMS, key=lambda i: int(i[1:])):
        out.append(f"| {item} | {', '.join(sorted(matrix.by_upstream(item)))} |")
    for pointer in matrix.pointers:
        out.append(
            f"| {pointer.finding} | not classified: {pointer.destination}. {pointer.reason} |"
        )
    out += [
        "",
        "## Binding-source classifier placement",
        "",
        "| Kind | Row | Outcome | Code | Evidence |",
        "|---|---|---|---|---|",
    ]
    for p in matrix.classifier:
        out.append(
            f"| {p.kind} | {p.row} | {p.outcome.value} | {p.code} | {', '.join(f'`{e}`' for e in p.evidence)} |"
        )
    out += ["", "## Rows", ""]
    for row in matrix.values():
        out += _row_section(row)
    return "\n".join(out).rstrip() + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args()
    args.out.write_text(render(load_matrix()), encoding="utf-8")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
