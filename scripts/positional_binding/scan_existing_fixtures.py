"""Run the positional-binding check over every existing fixture and list what it reports.

    uv run python scripts/positional_binding/scan_existing_fixtures.py

Plan Phase 5 step 5 (spec Det-8). Every directory under `tests/fixtures/` that holds a `.sysml`
file at any depth is loaded whole, as `agentic-mbse validate <dir>` would load it, except
`tests/fixtures/positional_binding/` (this item's own fixtures) and `tests/fixtures/` itself.
Loading whole directories keeps multi-file fixtures resolved; a result that appears only when
a subdirectory is loaded without its siblings is reported separately, as a partial-load result.

No pin list is used: the check is run as `validate` runs it on a tree with no project root, so
every mismatch is an ERROR. Writes `.project/completed/20261018_positional-binding-check/evidence/
existing-fixture-scan.md`. Everything from the "## Justification" heading on is kept on rerun.
"""

from __future__ import annotations

import sys
from collections import defaultdict
from pathlib import Path

from dotenv import load_dotenv

from agentic_mbse.sysml.syside_adapter import get_syside
from agentic_mbse.sysml.types import ValidationCode, ValidationIssue
from agentic_mbse.validation.common import discover_sysml_files, load_sysml_model
from agentic_mbse.validation.positional_check import check

REPO_ROOT = Path(__file__).resolve().parents[2]
FIXTURES = REPO_ROOT / "tests" / "fixtures"
OWN = FIXTURES / "positional_binding"
OUT = (
    REPO_ROOT
    / ".project/completed/20261018_positional-binding-check/evidence/existing-fixture-scan.md"
)
KEEP_FROM = "## Justification"
REPORTED = {
    ValidationCode.L2_POSITIONAL_BINDING,
    ValidationCode.L2_CHECK_UNVERIFIABLE,
    ValidationCode.L2_POSITIONAL_PIN_STALE,
    ValidationCode.L2_POSITIONAL_PIN_LIST_INVALID,
}


def load_roots() -> list[Path]:
    roots: set[Path] = set()
    for path in FIXTURES.rglob("*.sysml"):
        if OWN in path.parents:
            continue
        for parent in path.parents:
            if parent == FIXTURES:
                break
            roots.add(parent)
    return sorted(roots)


def scan(root: Path) -> tuple[list[ValidationIssue], dict[str, object]]:
    files = discover_sysml_files(str(root))
    model, _ = load_sysml_model(files)
    return check(model, root, files, None, None)


def key(issue: ValidationIssue) -> tuple[str, str, str, str]:
    return (issue.code.value, issue.reason_code or "", issue.location, issue.element_name)


def main() -> int:
    load_dotenv(REPO_ROOT / ".env")
    get_syside()
    roots = load_roots()
    seen: dict[tuple[str, str, str, str], list[Path]] = defaultdict(list)
    messages: dict[tuple[str, str, str, str], str] = {}
    inspected: dict[Path, object] = {}
    for root in roots:
        issues, metrics = scan(root)
        inspected[root] = metrics["Positional inputs inspected"]
        for issue in issues:
            if issue.code in REPORTED:
                seen[key(issue)].append(root)
                messages[key(issue)] = issue.message
    # A result holds for the fixture when every loaded directory containing its file reports
    # it. Otherwise it depends on how much was loaded: a subdirectory without its siblings
    # (unresolved references) or a parent that merges variants with clashing package names.
    containing = {
        item: [r for r in roots if r in (REPO_ROOT / item[2].rsplit(":", 1)[0]).parents]
        for item in seen
    }
    whole: list[Row] = []
    partial: list[Row] = []
    for item, where in sorted(seen.items()):
        (whole if set(containing[item]) == set(where) else partial).append((item, where))
    lines = [
        "# Existing-fixture scan (plan Phase 5 step 5, spec Det-8)",
        "",
        "Generated by `scripts/positional_binding/scan_existing_fixtures.py`. The listing above "
        "the Justification heading is regenerated on every run; the justification is kept.",
        "",
        f"- Load roots: {len(roots)} directories under `tests/fixtures/` (excluding "
        "`positional_binding/`), each loaded whole with its subdirectories, no pin list.",
        f"- Positional inputs inspected, summed over load roots: "
        f"{sum(int(str(v)) for v in inspected.values())}.",
        f"- Results every loaded directory containing the file reports: {len(whole)}.",
        f"- Results that depend on how much was loaded: {len(partial)}.",
        "",
        "## Results that hold however the fixture is loaded",
        "",
    ]
    lines += _table(whole) if whole else ["None."]
    lines += ["", "## Results that depend on how much was loaded", ""]
    lines += _table(partial, containing) if partial else ["None."]
    lines += ["", "## Messages", ""]
    for item, _ in whole + partial:
        lines.append(f"- `{item[2]}` {item[0]}: {messages[item]}")
    if not whole and not partial:
        lines.append("None.")
    kept = ""
    if OUT.exists() and KEEP_FROM in OUT.read_text():
        kept = OUT.read_text()[OUT.read_text().index(KEEP_FROM) :]
    OUT.write_text("\n".join(lines) + "\n\n" + (kept or f"{KEEP_FROM}\n\n(to be written)\n"))
    print(f"wrote {OUT.relative_to(REPO_ROOT)}: {len(whole)} whole, {len(partial)} partial")
    return 0


Row = tuple[tuple[str, str, str, str], list[Path]]


def _table(
    rows: list[Row], containing: dict[tuple[str, str, str, str], list[Path]] | None = None
) -> list[str]:
    header = "| Code | Reason | Location | Element | Loads reporting it |"
    rule = "|---|---|---|---|---|"
    if containing is not None:
        header += " Loads containing the file that do not |"
        rule += "---|"
    out = [header, rule]
    for item, where in rows:
        code, reason, location, element = item
        row = f"| {code} | {reason} | `{location}` | `{element}` | {_roots(where)} |"
        if containing is not None:
            row += f" {_roots([r for r in containing[item] if r not in where])} |"
        out.append(row)
    return out


def _roots(roots: list[Path]) -> str:
    return ", ".join(f"`{r.relative_to(FIXTURES)}`" for r in roots) or "none"


if __name__ == "__main__":
    sys.exit(main())
