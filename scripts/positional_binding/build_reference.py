"""Build the fusion-tea positional pin list from the prototype's tree log, and nothing else.

    uv run python scripts/positional_binding/build_reference.py

Design Appendix B "Reference file", I3. Reads
`.project/concepts/convince-me-exec-subset/evidence/04-detector-tree-fusion-tea.log`, which the
prototype detector wrote for fusion-tea `f96ad312` with SysIDE 0.8.4. Each finding is two lines:

      L2_POSITIONAL_BINDING  //designs/aries_cs_integrated/plant.sysml:270  <input qualified name>
          input '<declared name>' implicitly redefines '<target qualified name>' by position; ...

The file is relative to fusion-tea's `models/`, so the pin's file is `models/<path>`. The owner
is the input's qualified name without its last segment, which must equal the declared name. The
target is the text between the first `'` after "redefines " and `' by position`, so its own
inner quotes survive. Writes `tests/fixtures/positional_binding/baselines/fusion-tea-f96ad312.toml`
after checking 125 entries, 125 distinct identities and 9 distinct files.
"""

from __future__ import annotations

import re
import sys
from dataclasses import dataclass
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
PROTOTYPE_LOG = (
    REPO_ROOT / ".project/concepts/convince-me-exec-subset/evidence/04-detector-tree-fusion-tea.log"
)
OUT = REPO_ROOT / "tests/fixtures/positional_binding/baselines/fusion-tea-f96ad312.toml"
REVISION = "f96ad312c63e8c66695971b12feab971f3ba6eb3"
RECORDED = "2026-10-15"
EXPECTED_ENTRIES = 125
EXPECTED_FILES = 9

_FINDING = re.compile(r"^  L2_POSITIONAL_BINDING  //(?P<file>\S+):(?P<line>\d+)  (?P<input>\S.*)$")
_DETAIL = re.compile(r"^      input '(?P<name>[^']+)' implicitly redefines '")
_TARGET_END = "' by position"


class LogFormatError(ValueError):
    """The log does not have the shape the builder reads; nothing is written."""


@dataclass(frozen=True, order=True)
class Entry:
    owner: str
    input: str
    target: str
    file: str
    line: int


def parse_log(log: Path) -> list[Entry]:
    lines = log.read_text().splitlines()
    entries: list[Entry] = []
    for index, text in enumerate(lines):
        finding = _FINDING.match(text)
        if finding is None:
            continue
        if index + 1 >= len(lines):
            raise LogFormatError(f"line {index + 1}: finding without its detail line")
        detail = lines[index + 1]
        named = _DETAIL.match(detail)
        if named is None or _TARGET_END not in detail:
            raise LogFormatError(f"line {index + 2}: unexpected detail line {detail!r}")
        start = named.end()
        target = detail[start : detail.index(_TARGET_END, start)]
        input_qualified = finding["input"].strip()
        owner, _, last = input_qualified.rpartition("::")
        declared = named["name"]
        if not owner or last.strip("'") != declared:
            raise LogFormatError(
                f"line {index + 1}: input {input_qualified} does not end in its declared "
                f"name {declared!r}"
            )
        entries.append(
            Entry(owner, declared, target, f"models/{finding['file']}", int(finding["line"]))
        )
    return entries


def _toml_string(value: str) -> str:
    if '"' in value or "\\" in value or any(ord(c) < 0x20 for c in value):
        raise LogFormatError(f"{value!r} needs escaping; the builder writes plain strings only")
    return f'"{value}"'


def render(entries: list[Entry]) -> str:
    out = [
        "# fusion-tea f96ad312 positional pins, generated by",
        "# scripts/positional_binding/build_reference.py from",
        "# .project/concepts/convince-me-exec-subset/evidence/04-detector-tree-fusion-tea.log.",
        "# Evidence for the owner's R4-3 decision; not installed in fusion-tea. A pin certifies",
        "# nothing about native values or about agreement between the native and generated routes.",
        'schema = "positional-pins/v1"',
        "",
        "[recorded_against]",
        f'revision = "{REVISION}"',
        f"date = {RECORDED}",
    ]
    for entry in sorted(entries):
        out += [
            "",
            "[[pin]]",
            f"owner = {_toml_string(entry.owner)}",
            f"input = {_toml_string(entry.input)}",
            f"target = {_toml_string(entry.target)}",
            f"file = {_toml_string(entry.file)}",
            f"line = {entry.line}",
        ]
    return "\n".join(out) + "\n"


def build_reference(log: Path, out: Path) -> None:
    entries = parse_log(log)
    identities = {(e.owner, e.input, e.target) for e in entries}
    files = {e.file for e in entries}
    if (len(entries), len(identities), len(files)) != (
        EXPECTED_ENTRIES,
        EXPECTED_ENTRIES,
        EXPECTED_FILES,
    ):
        raise LogFormatError(
            f"expected {EXPECTED_ENTRIES} entries, {EXPECTED_ENTRIES} distinct identities and "
            f"{EXPECTED_FILES} files; got {len(entries)}, {len(identities)}, {len(files)}"
        )
    out.write_text(render(entries))


def main() -> int:
    build_reference(PROTOTYPE_LOG, OUT)
    print(f"wrote {OUT.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
